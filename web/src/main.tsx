// Flowie in the browser: the outline as pages of bullets (zoom into any bullet, breadcrumbs
// back), with keyboard editing, over the Rust core in wasm. The core runs in a worker
// (worker/index.ts) with the outline kept in OPFS, synced with the flowie-server this page
// comes from. State lives in signals (state/), drawn by Preact components by feature.
import { render } from "preact";
import { App } from "./app/App";
import { start } from "./app/start";
import { status } from "./state/session";
import "./styles/tokens.css";
import "./styles/app.css";

render(<App />, document.getElementById("app")!);

// Keep the page's files for opening offline (sw.js, generated by the build); the outline is in
// OPFS already.
if (import.meta.env.PROD && "serviceWorker" in navigator) {
  navigator.serviceWorker.register("sw.js").catch((error: unknown) => console.warn("Flowie: no offline page:", error));
}

start().catch((error: unknown) => {
  status.value = `error: ${error instanceof Error ? error.message : String(error)}`;
  console.error(error);
});
